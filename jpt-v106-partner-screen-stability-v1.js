/* JPT V106 PARTNER SCREEN-STABILITY HOTFIX v1
   Safe overlay for the existing Partner App.
   Goal: stop visible up/down jumps caused by repeated loadOrders() renders.
   Does not replace order logic, alarm logic, payment gate, or Supabase config.
*/
(function () {
  "use strict";

  if (window.__JPT_V106_SCREEN_STABILITY_V1__) return;
  window.__JPT_V106_SCREEN_STABILITY_V1__ = true;

  const original = window.loadOrders;
  if (typeof original !== "function") {
    // Partner hotfix may still be loading. Retry briefly.
    let tries = 0;
    const t = setInterval(() => {
      tries++;
      if (typeof window.loadOrders === "function") {
        clearInterval(t);
        install(window.loadOrders);
      } else if (tries > 40) {
        clearInterval(t);
      }
    }, 250);
  } else {
    install(original);
  }

  function install(baseLoadOrders) {
    if (window.__JPT_V106_SCREEN_STABILITY_INSTALLED__) return;
    window.__JPT_V106_SCREEN_STABILITY_INSTALLED__ = true;

    let running = false;
    let queued = false;
    let lastRun = 0;
    let lastError = null;

    function captureViewport() {
      const y = window.scrollY || window.pageYOffset || 0;
      const active = document.activeElement;
      let focusId = null;
      let focusStart = 0;

      if (active && active.id) {
        focusId = active.id;
        try { focusStart = active.selectionStart || 0; } catch (_) {}
      }

      // Capture the currently visible order number as a stable anchor.
      let anchorText = "";
      let anchorTop = 0;
      const cards = document.querySelectorAll(".order");
      let best = null;
      let bestDistance = Infinity;

      cards.forEach(card => {
        const r = card.getBoundingClientRect();
        if (r.bottom <= 0 || r.top >= window.innerHeight) return;
        const d = Math.abs(r.top - 140);
        if (d < bestDistance) {
          bestDistance = d;
          best = card;
        }
      });

      if (best) {
        const top = best.getBoundingClientRect().top;
        anchorTop = top;
        const first = best.querySelector(".order-top b");
        anchorText = first ? String(first.textContent || "").trim() : "";
      }

      return { y, focusId, focusStart, anchorText, anchorTop };
    }

    function restoreViewport(v) {
      // If the user has deliberately scrolled while the request was running,
      // do not fight their gesture.
      const currentY = window.scrollY || window.pageYOffset || 0;
      if (Math.abs(currentY - v.y) > 140) return;

      if (v.anchorText) {
        const cards = document.querySelectorAll(".order");
        for (const card of cards) {
          const first = card.querySelector(".order-top b");
          if (!first) continue;
          if (String(first.textContent || "").trim() !== v.anchorText) continue;

          const nowTop = card.getBoundingClientRect().top;
          const delta = nowTop - v.anchorTop;
          if (Math.abs(delta) > 1 && Math.abs(delta) < 500) {
            window.scrollBy(0, delta);
          }
          break;
        }
      } else {
        window.scrollTo(0, v.y);
      }

      if (v.focusId) {
        const el = document.getElementById(v.focusId);
        if (el && document.activeElement !== el) {
          try {
            el.focus({ preventScroll: true });
            if (typeof el.setSelectionRange === "function") {
              el.setSelectionRange(v.focusStart, v.focusStart);
            }
          } catch (_) {}
        }
      }
    }

    window.loadOrders = async function () {
      const now = Date.now();

      // Collapse duplicate calls generated by multiple legacy polling bridges.
      if (running) {
        queued = true;
        return;
      }

      // Never re-render the whole order list more than once per 1500 ms.
      if (now - lastRun < 1500) return;

      running = true;
      queued = false;
      lastRun = now;

      const viewport = captureViewport();

      try {
        await baseLoadOrders();
        lastError = null;
      } catch (e) {
        lastError = e;
        throw e;
      } finally {
        // Restore position after DOM replacement has settled.
        requestAnimationFrame(() => {
          requestAnimationFrame(() => restoreViewport(viewport));
        });

        running = false;

        // One queued refresh only; never create a refresh storm.
        if (queued) {
          queued = false;
          setTimeout(() => {
            if (typeof window.loadOrders === "function") {
              window.loadOrders().catch(() => {});
            }
          }, 1200);
        }
      }
    };

    // Countdown remains independent of list refreshes.
    // No extra interval is created here.
  }
})();
